// WHY THIS IS A FILE AND NOT A LOOKUP SERVICE
//
// The record-or-not decision is a SYNCHRONOUS step in call setup: recording has to be
// configured on the Twilio call before any media flows. A network call here would put a
// third-party's latency — and its outages — directly in front of every dial. So the
// table ships in the repo, in process, and answers in microseconds.
//
// WHERE IT CAME FROM
//
// Generated on 2026-08-19 from the public NANPA area-code list
// (https://en.wikipedia.org/wiki/List_of_North_American_Numbering_Plan_area_codes),
// filtered to codes serving a US state, the District of Columbia, or a US territory.
// Canadian and Caribbean NPAs are deliberately ABSENT: this table answers "which US
// state", and a Toronto number has no answer to that question. `usStateForE164` returns
// null for them, which `recordingDecision.ts` treats as `unknown` — not as "one-party".
//
// Area codes change slowly (a handful of overlays a year) and the failure mode of a
// stale entry is bounded: one NPA is classified `unknown` instead of its real state, and
// `unknown` takes the safer path. That is why this is refreshed by hand, not fetched.
//
// NOT LEGAL ADVICE. This maps digits to a state. Whether recording is lawful is
// `consentStates.ts`, and that file says the same thing about itself.

