/**
 * The area code of a US/Canada E.164 number, or null.
 *
 * Only `+1` numbers have an NPA at all. Anything else — a UK number, a malformed
 * string — returns null rather than slicing three digits out of the middle of it and
 * pretending they mean something.
 */
export function npaOf(e164: string): string | null {
  // +1 followed by exactly 10 digits. The first digit of the NPA and of the exchange
  // are both 2-9 in the numbering plan, so a `+1` number that fails this is not a real
  // one and should not silently match a table entry.
  const match = /^\+1([2-9]\d{2})[2-9]\d{6}$/.exec(e164.trim());
  return match?.[1] ?? null;
}

/**
 * Which US state or territory this number's area code serves, or null when we cannot
 * tell — a non-US number, a Canadian NPA, or a code newer than this table.
 *
 * Null is a real answer here, not a failure. The caller is required to handle it as
 * `unknown` (journey 2.3 step 2), and `unknown` is not the same as "one-party".
 */
export function usStateForE164(e164: string): string | null {
  const npa = npaOf(e164);
  if (!npa) return null;
  return NPA_TO_STATE[npa] ?? null;
}
